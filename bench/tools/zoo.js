// Silent bug zoo: one page per kind of silent failure (https://senyap-demo.vercel.app/zoo/?bug=<kind>),
// each run with plain Kane (A) and with Senyap (B), one Kane run at a time.
// usage: node bench/tools/zoo.js [kind...]   -> bench/zoo-results.json + bench/ZOO.md
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { kane } from '../../src/kane.js';
import { huntFlow } from '../../src/hunt.js';

const BENCH = resolve(fileURLToPath(import.meta.url), '../..');
const OUT = join(BENCH, 'zoo-results.json');
const BASE = 'https://senyap-demo.vercel.app/zoo/?bug=';
const FLOW = 'Add a note that says "Buy oat milk" and save it';
export const KINDS = ['http_5xx', 'http_4xx', 'request_failed', 'console_error', 'js_exception', 'env_leak', 'test_key', 'none'];

const results = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : {};
const save = () => { writeFileSync(OUT, JSON.stringify(results, null, 2)); writeFileSync(join(BENCH, 'ZOO.md'), render(results)); };

async function plainKane(url) {
  const r = await kane(['run', `${FLOW}. Then verify that it worked.`, '--url', url, '--agent', '--headless', '--bug-detection', 'continue', '--timeout', '300'], { timeoutSec: 300 });
  const e = r.end ?? {};
  return { status: e.status ?? 'not_run', result_code: e.result_code ?? null, reason_code: e.reason_code ?? null, test_url: e.test_url ?? null, credits: e.credits_consumed ?? null, exitCode: r.exitCode };
}

const caughtA = (a) => a.status === 'failed' && a.result_code === 740;
const caughtB = (b) => b.status === 'silent_failure' || b.status === 'failed';

export function render(res) {
  const rows = KINDS.filter((k) => res[k]).map((k) => {
    const { A, B } = res[k];
    const a = A ? `${caughtA(A) ? '**caught**' : A.status === 'passed' ? 'passed' : 'no verdict'} (${A.result_code ?? A.exitCode})` : '';
    const b = B ? `${caughtB(B) ? '**caught**' : B.status} (${B.kane?.result_code ?? ''}${B.findings?.length ? `; ${[...new Set(B.findings.filter((f) => f.severity === 'blocking').map((f) => f.kind))].join(', ')}` : ''})` : '';
    const links = [A?.test_url && `[A](${A.test_url})`, B?.kane?.test_url && `[B](${B.kane.test_url})`].filter(Boolean).join(' · ');
    return `| [\`${k}\`](${BASE}${k}) | ${a} | ${b} | ${links} |`;
  });
  const bugs = KINDS.filter((k) => k !== 'none' && res[k]?.A && res[k]?.B);
  const credits = Object.values(res).reduce((s, r) => s + (r.A?.credits ?? 0) + (r.B?.credits ?? r.B?.kane?.credits ?? 0), 0);
  return [
    '# Silent bug zoo',
    '',
    `Every page looks the same and always says "Saved!". \`?bug=\` picks what breaks underneath. Flow for every row: \`${FLOW}\`. A is plain \`kane-cli run "<flow>. Then verify that it worked." --bug-detection continue\`; B is \`senyap hunt\` (no reload check: the zoo stores nothing). One Kane run at a time. Generated by \`bench/tools/zoo.js\`.`,
    '',
    '| Kind | Plain Kane (A) | Senyap (B) | Kane runs |',
    '|---|---|---|---|',
    ...rows,
    '',
    `Caught: plain Kane ${bugs.filter((k) => caughtA(res[k].A)).length}/${bugs.length}, Senyap ${bugs.filter((k) => caughtB(res[k].B)).length}/${bugs.length}. Control page (\`none\`): plain Kane ${res.none?.A?.status ?? 'n/a'}, Senyap ${res.none?.B?.status ?? 'n/a'}. Credits: ${credits.toFixed(1)}.`,
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const kinds = process.argv.slice(2).length ? process.argv.slice(2) : KINDS;
  const work = join(BENCH, '..', '.senyap', 'zoo');
  mkdirSync(work, { recursive: true });
  for (const k of kinds) {
    const url = BASE + k;
    results[k] ??= {};
    if (!results[k].A) { results[k].A = await plainKane(url); save(); console.error(k, 'A', results[k].A.status, results[k].A.result_code); }
    if (!results[k].B) {
      const b = await huntFlow({ url, flow: FLOW, persistence: false, workDir: work });
      results[k].B = { status: b.status, credits: b.credits ?? b.kane.credits, kane: b.kane, findings: b.findings.map(({ kind, severity, method, url: u, status, detail }) => ({ kind, severity, method, url: u, status, detail: detail?.slice(0, 160) })), observe: b.observe, confirm: b.confirm };
      save();
      console.error(k, 'B', results[k].B.status, results[k].B.kane.result_code);
    }
  }
}
